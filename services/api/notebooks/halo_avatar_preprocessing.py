def get_feature_confidence(pose_result, landmark_ids):

    landmarks = pose_result.pose_landmarks[0]

    confidences = [
        landmarks[index].visibility
        for index in landmark_ids
    ]

    return sum(confidences) / len(confidences)


def fuse_body_features(front_result, back_result,
                       front_features, back_features):

    feature_landmarks = {
        "shoulder_to_height_ratio": [0, 11, 12, 27, 28],
        "hip_to_height_ratio": [0, 23, 24, 27, 28],
        "torso_to_height_ratio": [0, 11, 12, 23, 24, 27, 28],
        "upper_leg_to_height_ratio": [0, 23, 24, 25, 26, 27, 28],
        "lower_leg_to_height_ratio": [0, 25, 26, 27, 28],
        "upper_arm_to_height_ratio": [0, 11, 12, 13, 14, 27, 28],
        "lower_arm_to_height_ratio": [0, 13, 14, 15, 16, 27, 28]
    }

    fused_features = {}

    for feature_name, landmark_ids in feature_landmarks.items():

        front_value = front_features.get(feature_name)
        back_value = back_features.get(feature_name)

        if front_value is None or back_value is None:
            continue

        front_confidence = get_feature_confidence(
            front_result, landmark_ids
        )

        back_confidence = get_feature_confidence(
            back_result, landmark_ids
        )

        total_confidence = front_confidence + back_confidence

        if total_confidence == 0:
            continue

        fused_value = (
            front_value * front_confidence +
            back_value * back_confidence
        ) / total_confidence

        fused_features[feature_name] = fused_value

    return fused_features

