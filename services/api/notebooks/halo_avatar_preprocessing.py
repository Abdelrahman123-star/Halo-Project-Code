def extract_silhouette_features(binary_mask):

    height, width = binary_mask.shape

    body_profile = {}

    # Sample 20 positions from top to bottom
    vertical_positions = np.linspace(
        0.10, 0.95, 20
    )

    for position in vertical_positions:

        y = int(position * height)

        row = binary_mask[y, :]

        foreground_pixels = np.where(row == 1)[0]

        if len(foreground_pixels) > 0:

            left_edge = foreground_pixels.min()
            right_edge = foreground_pixels.max()

            body_width = right_edge - left_edge + 1

            body_profile[round(position, 2)] = {
                "left_edge": int(left_edge),
                "right_edge": int(right_edge),
                "width_px": int(body_width),
                "width_ratio": body_width / width
            }

    return body_profile


