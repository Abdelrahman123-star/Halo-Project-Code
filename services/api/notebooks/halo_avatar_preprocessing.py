import numpy as np

def extract_body_features(pose_result, image_shape):

    landmarks = pose_result.pose_landmarks[0]

    height, width = image_shape[:2]

    # Convert normalized coordinates into pixel coordinates
    points = {}

    for i, landmark in enumerate(landmarks):
        points[i] = np.array([
            landmark.x * width,
            landmark.y * height
        ])

    # Calculate distance between two landmarks
    def distance(point_a, point_b):
        return float(np.linalg.norm(
            points[point_a] - points[point_b]
        ))

    # Midpoint between left and right landmarks
    def midpoint(point_a, point_b):
        return (points[point_a] + points[point_b]) / 2

    # Main body measurements in pixels
    shoulder_width = distance(11, 12)
    hip_width = distance(23, 24)

    shoulder_center = midpoint(11, 12)
    hip_center = midpoint(23, 24)

    torso_length = float(np.linalg.norm(
        shoulder_center - hip_center
    ))

    # Arm lengths (average left and right)
    upper_arm = (
        distance(11, 13) + distance(12, 14)
    ) / 2

    lower_arm = (
        distance(13, 15) + distance(14, 16)
    ) / 2

    # Leg lengths (average left and right)
    upper_leg = (
        distance(23, 25) + distance(24, 26)
    ) / 2

    lower_leg = (
        distance(25, 27) + distance(26, 28)
    ) / 2

    # Approximate visible body height:
    # Nose to average ankle position
    ankle_center = midpoint(27, 28)

    visible_height = float(np.linalg.norm(
        points[0] - ankle_center
    ))

    # Calculate relative proportions
    features = {
        "shoulder_width_px": shoulder_width,
        "hip_width_px": hip_width,
        "torso_length_px": torso_length,
        "upper_arm_length_px": upper_arm,
        "lower_arm_length_px": lower_arm,
        "upper_leg_length_px": upper_leg,
        "lower_leg_length_px": lower_leg,
        "visible_height_px": visible_height,

        "shoulder_to_height_ratio":
            shoulder_width / visible_height,

        "hip_to_height_ratio":
            hip_width / visible_height,

        "torso_to_height_ratio":
            torso_length / visible_height,

        "upper_leg_to_height_ratio":
            upper_leg / visible_height,

        "lower_leg_to_height_ratio":
            lower_leg / visible_height
    }

    return features

