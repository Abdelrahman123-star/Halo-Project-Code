def clean_silhouette(binary_mask):

    # Convert mask to 8-bit format
    mask = (binary_mask * 255).astype(np.uint8)

    # Create a small morphological kernel
    kernel = cv2.getStructuringElement(
        cv2.MORPH_ELLIPSE,
        (3, 3)
    )

    # Remove small white noise
    opened_mask = cv2.morphologyEx(
        mask,
        cv2.MORPH_OPEN,
        kernel
    )

    # Fill small black gaps
    closed_mask = cv2.morphologyEx(
        opened_mask,
        cv2.MORPH_CLOSE,
        kernel
    )

    # Find connected foreground components
    num_labels, labels, stats, centroids = (
        cv2.connectedComponentsWithStats(
            closed_mask,
            connectivity=8
        )
    )

    # Keep the largest foreground component
    if num_labels > 1:

        largest_component = 1 + np.argmax(
            stats[1:, cv2.CC_STAT_AREA]
        )

        cleaned_mask = (
            labels == largest_component
        ).astype(np.uint8)

    else:
        cleaned_mask = (
            closed_mask > 0
        ).astype(np.uint8)

    return cleaned_mask


